"""Macro and FeaturePython scaffold generator (F6).

``macro_source`` writes a ``.FCMacro`` whose ``run(doc)`` does the work and which calls it
when executed as ``__main__`` (how FreeCAD runs a macro). ``featurepython_source`` writes a
custom-feature module: a proxy class with ``execute``, ``onChanged``, ``dumps`` and ``loads``,
a ``make`` helper, and a ViewProvider stub that exists only under ``if FreeCAD.GuiUp:`` and
imports ``FreeCADGui`` only there, so importing the module headless never touches the GUI.
Generated text passes pyright against ``freecad-stubs`` (see ``grounding``).

``write_macro``, ``write_feature_module`` and ``register`` save the files into a macro
directory and record them in its ``registry.json``; ``load_feature_module`` imports one.
Callers choose the directory. Tests use a temporary one, never ``getUserMacroDir``.
"""

import importlib.util
import json
import keyword
import os
import re
import sys
import textwrap

_HEADER = "# -*- coding: utf-8 -*-\n# SPDX-License-Identifier: LGPL-2.1-or-later\n"


def _ident(text):
    out = re.sub(r"\W", "_", text).strip("_") or "Generated"
    if out[0].isdigit() or keyword.iskeyword(out):
        out = "_" + out
    return out


def _indent(text, n):
    text = textwrap.dedent(text).strip("\n")
    return textwrap.indent(text, " " * n) if text else " " * n + "pass"


def macro_source(name, description, body, *, recompute=True):
    """A ``.FCMacro`` text. ``body`` is statements that use ``doc`` (a FreeCAD document)."""
    fn = _ident(name)
    one_line = " ".join(description.split())
    return (
        f"{_HEADER}# Macro: {fn}\n# Description: {one_line}\n# Generated by AgentCore.refactor.scaffold\n"
        "import FreeCAD\n\n\n"
        f"def run(doc=None):\n    \"\"\"{one_line}\"\"\"\n"
        f"    doc = doc or FreeCAD.ActiveDocument or FreeCAD.newDocument(\"{fn}\")\n"
        f"{_indent(body, 4)}\n"
        + ("    doc.recompute()\n" if recompute else "")
        + "    return doc\n\n\n"
        "if __name__ == \"__main__\":\n    run()\n"
    )


_PROP_DEFAULTS = {"App::PropertyLength": 10.0, "App::PropertyAngle": 0.0, "App::PropertyFloat": 1.0,
                  "App::PropertyInteger": 1, "App::PropertyString": "", "App::PropertyBool": False}


def featurepython_source(class_name, properties=None, execute_body=None, on_changed_body=None, doc=None):
    """A custom-feature module text.

    ``properties``: list of ``{"name", "type", "group", "doc", "default"}``; default
    ``Length``, ``Width`` and ``Height`` lengths. ``execute_body`` runs with ``obj`` and ``Part``
    in scope and must assign ``obj.Shape``; the default builds a box from the three properties.
    """
    cls = _ident(class_name)
    props = properties or [
        {"name": "Length", "type": "App::PropertyLength", "group": "Base", "doc": "Box length", "default": 10.0},
        {"name": "Width", "type": "App::PropertyLength", "group": "Base", "doc": "Box width", "default": 20.0},
        {"name": "Height", "type": "App::PropertyLength", "group": "Base", "doc": "Box height", "default": 30.0},
    ]
    execute_body = execute_body or "obj.Shape = Part.makeBox(obj.Length.Value, obj.Width.Value, obj.Height.Value)"
    on_changed_body = on_changed_body or "pass"
    adds = []
    for p in props:
        default = p.get("default", _PROP_DEFAULTS.get(p["type"], 0))
        adds.append(f"        obj.addProperty({p['type']!r}, {p['name']!r}, {p.get('group', 'Base')!r}, {p.get('doc', '')!r})\n"
                    f"        obj.{p['name']} = {default!r}")
    summary = " ".join((doc or f"{cls}: generated FeaturePython feature.").split())
    return (
        f"{_HEADER}\"\"\"{summary}\"\"\"\n"
        "import FreeCAD\nimport Part\n\n\n"
        f"class {cls}:\n    \"\"\"Proxy for a Part::FeaturePython object.\"\"\"\n\n"
        "    def __init__(self, obj):\n"
        "        obj.Proxy = self\n"
        "        self.version = 1\n"
        + "\n".join(adds) + "\n\n"
        "    def execute(self, obj):\n"
        f"{_indent(execute_body, 8)}\n\n"
        "    def onChanged(self, obj, prop):\n"
        f"{_indent(on_changed_body, 8)}\n\n"
        "    def dumps(self):\n"
        "        return {\"version\": self.version}\n\n"
        "    def loads(self, state):\n"
        "        self.version = (state or {}).get(\"version\", 1)\n\n\n"
        "if FreeCAD.GuiUp:\n"
        "    import FreeCADGui  # noqa: F401  (only reached with a GUI)\n\n"
        f"    class ViewProvider{cls}:\n"
        "        \"\"\"View provider stub; never imported or instantiated headless.\"\"\"\n\n"
        "        def __init__(self, vobj):\n"
        "            vobj.Proxy = self\n\n"
        "        def attach(self, vobj):\n"
        "            self.Object = vobj.Object\n\n"
        "        def getIcon(self):\n"
        "            return \"\"\n\n"
        "        def dumps(self):\n"
        "            return None\n\n"
        "        def loads(self, state):\n"
        "            return None\n\n\n"
        f"def make(doc=None, name=\"{cls}\"):\n"
        "    doc = doc or FreeCAD.ActiveDocument or FreeCAD.newDocument(name)\n"
        "    obj = doc.addObject(\"Part::FeaturePython\", name)\n"
        f"    {cls}(obj)\n"
        "    if FreeCAD.GuiUp:\n"
        f"        ViewProvider{cls}(obj.ViewObject)\n"
        "    doc.recompute()\n"
        "    return obj\n"
    )


def _registry_path(directory):
    return os.path.join(directory, "registry.json")


def register(directory, kind, name, filename, **extra):
    """Record a generated file in ``<directory>/registry.json`` (kind: ``macro`` or ``feature``)."""
    path = _registry_path(directory)
    reg = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            reg = json.load(fh)
    reg[name] = {"kind": kind, "file": filename, **extra}
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(reg, fh, indent=2, sort_keys=True)
        fh.write("\n")
    return reg


def write_macro(directory, name, description, body, **kw):
    """Write ``<name>.FCMacro`` into ``directory`` and register it; returns the path."""
    os.makedirs(directory, exist_ok=True)
    fn = _ident(name)
    path = os.path.join(directory, fn + ".FCMacro")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(macro_source(name, description, body, **kw))
    register(directory, "macro", fn, os.path.basename(path), description=" ".join(description.split()))
    return path


def write_feature_module(directory, class_name, **kw):
    """Write ``<class_name>.py`` (a FeaturePython module) into ``directory`` and register it."""
    os.makedirs(directory, exist_ok=True)
    cls = _ident(class_name)
    path = os.path.join(directory, cls + ".py")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(featurepython_source(cls, **kw))
    register(directory, "feature", cls, os.path.basename(path), module=cls)
    return path


def load_feature_module(directory, class_name):
    """Import a registered feature module with ``directory`` on ``sys.path`` (needed to reload its Proxy)."""
    cls = _ident(class_name)
    if directory not in sys.path:
        sys.path.insert(0, directory)
    sys.modules.pop(cls, None)
    spec = importlib.util.spec_from_file_location(cls, os.path.join(directory, cls + ".py"))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[cls] = mod
    spec.loader.exec_module(mod)
    return mod


def run_macro_file(path, doc=None):
    """Execute a ``.FCMacro`` the way FreeCAD does (as ``__main__``) and return its namespace."""
    with open(path, encoding="utf-8") as fh:
        code = compile(fh.read(), path, "exec")
    ns = {"__name__": "__main__", "__file__": path}
    if doc is not None:
        import FreeCAD
        FreeCAD.setActiveDocument(doc.Name)
    exec(code, ns)
    return ns
