"""The command index of the palette.

Commands of workbenches that are not loaded yet are not registered with the command manager, so the palette ships an
index (commands_index.json, generated by harness/gui/palette_index.py in the workshop, which activates every workbench
once) and merges the live command table over it at every open: loaded commands show their current text, commands
registered later (macros, add-ons) appear, and the shipped index only has to carry what is not registered yet.
`python3 -I harness/gui/palette_index.py` is not needed to keep it fresh in normal use: the freshness check
(`run_gui.py script harness/gui/palette_index.py --arg check=1`) lists commands missing from it or no longer there."""

import json
import os
import re

INDEX_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "commands_index.json")

# Command-name prefix -> workbench class name. C++ modules register their commands as a side effect of whichever workbench
# is activated first, so a before/after diff misattributes them; the prefix is what names the owner. Prefixes absent here
# fall back to the workbench whose first activation added the command.
WB_BY_PREFIX = {
    "Part": "PartWorkbench", "PartDesign": "PartDesignWorkbench", "Sketcher": "SketcherWorkbench",
    "TechDraw": "TechDrawWorkbench", "FEM": "FemWorkbench", "BIM": "BIMWorkbench", "Arch": "BIMWorkbench",
    "IFC": "BIMWorkbench", "Draft": "DraftWorkbench", "CAM": "CAMWorkbench", "Mesh": "MeshWorkbench",
    "MeshPart": "MeshWorkbench", "Assembly": "AssemblyWorkbench", "SheetMetal": "SMWorkbench",
    "Spreadsheet": "SpreadsheetWorkbench", "OpenSCAD": "OpenSCADWorkbench", "Robot": "RobotWorkbench",
    "Reen": "ReverseEngineeringWorkbench", "Test": "TestWorkbench", "Weldment": "WeldmentWorkbench",
    "PDM": "PDMWorkbench", "Points": "PointsWorkbench", "Surface": "SurfaceWorkbench",
    "Inspection": "InspectionWorkbench", "Materials": "MaterialWorkbench", "Material": "MaterialWorkbench",
    "Start": "StartWorkbench", "Std": "", "AgentCore": "",
}

_TAG = re.compile(r"<[^>]+>")


def clean_text(s):
    s = _TAG.sub(" ", s or "").replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    s = re.sub(r"&(?![a-z]+;)", "", s)
    return re.sub(r"\s+", " ", s).strip()


def humanize(name):
    tail = name.split("_", 1)[-1]
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", tail).strip()


def entry_for(name, info, diff_wb=None, key=""):
    prefix = name.split("_", 1)[0]
    wb = WB_BY_PREFIX.get(prefix)
    if wb is None:
        wb = (diff_wb or {}).get(name, "")
    menu = clean_text(info.get("menuText", "")) or humanize(name)
    e = {"name": name, "menu": menu, "tip": clean_text(info.get("toolTip", ""))[:240], "wb": wb}
    if key:
        e["key"] = key    # default shortcut, for the conflict test
    return e


def snapshot(diff_wb, labels):
    """Entries for every command registered right now (used by the generator after the sweep)."""
    import FreeCADGui as Gui
    out = []
    for name in sorted(Gui.listCommands()):
        try:
            info = Gui.Command.get(name).getInfo()
        except Exception:
            info = {}
        try:
            key = Gui.Command.get(name).getShortcut()
        except Exception:
            key = ""
        out.append(entry_for(name, info, diff_wb, key))
    return out


def write(entries, labels, dest=INDEX_PATH):
    wbs = sorted({e["wb"] for e in entries if e["wb"]})
    wb_labels = {w: labels.get(w) or re.sub(r"Workbench$", "", w) for w in wbs}
    with open(dest, "w", encoding="utf-8") as f:    # one command per line keeps diffs readable
        f.write('{"version": 1, "workbenches": %s, "commands": [\n' % json.dumps(wb_labels, ensure_ascii=False, sort_keys=True))
        f.write(",\n".join(json.dumps(e, ensure_ascii=False, sort_keys=True) for e in entries))
        f.write("\n]}\n")


def load_shipped(path=INDEX_PATH):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["commands"], data["workbenches"]


def live_entries(known):
    """Entries for registered commands not in `known` (a set of names), plus the registered set."""
    import FreeCADGui as Gui
    live = set(Gui.listCommands())
    new = []
    for name in sorted(live - known):
        try:
            info = Gui.Command.get(name).getInfo()
        except Exception:
            info = {}
        new.append(entry_for(name, info))
    return new, live
